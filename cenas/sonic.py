def desenhar(oled):
    # Mantem a mesma aparencia do arquivo original:
    # fundo branco e imagem na posicao 0,0.
    oled.fill(1)
    oled.blit(imagem, 0, 0)
    oled.show()


def esperar_soltar(botao):
    while not botao.value():
        time.sleep_ms(10)


def run(oled, botaoA, botaoB):
    desenhar(oled)

    while True:
        # A retorna ao seletor de mapas.
        if not botaoA.value():
            esperar_soltar(botaoA)
            return "mapselect"

        # B fica reservado para futuras interacoes.
        if not botaoB.value():
            esperar_soltar(botaoB)
            desenhar(oled)

        time.sleep_ms(20)


